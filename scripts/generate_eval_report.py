"""Generates EVAL_REPORT.md: runs all 12 assignment test cases in-process
(no live server needed) and records the decision, full trace, and a
match/mismatch verdict for each, per the assignment's eval-report deliverable.
"""

import json
from decimal import Decimal
from pathlib import Path

from fastapi.testclient import TestClient

from src.main import app
from scripts.run_evals import map_plum_test_to_api_payload, _check_system_must

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BASE_DIR / "data"
OUT_FILE = BASE_DIR / "EVAL_REPORT.md"

client = TestClient(app)


def _expected(case: dict):
    expected = case.get("expected", {})
    decision = "NEEDS_MEMBER_ACTION" if expected.get("decision") is None else expected["decision"]
    if "approved_amount" in expected:
        amount = Decimal(str(expected["approved_amount"]))
    elif decision == "APPROVED":
        amount = Decimal(str(case["input"].get("claimed_amount", 0)))
    else:
        amount = Decimal(0)
    return decision, amount


def main():
    data = json.loads((DATA_DIR / "test_cases.json").read_text())
    cases = data["test_cases"]

    lines = [
        "# Eval Report",
        "",
        f"Generated by `scripts/generate_eval_report.py` against all {len(cases)} cases in `data/test_cases.json`, "
        "run in-process through the FastAPI app (no live server required).",
        "",
        "SCORE_PLACEHOLDER",
        "",
        "| Case | Name | Expected | Actual | Amount (exp/actual) | Result |",
        "|---|---|---|---|---|---|",
    ]

    detail_sections = []
    passed = 0

    for case in cases:
        case_id = case["case_id"]
        expected_decision, expected_amount = _expected(case)
        payload = map_plum_test_to_api_payload(case)
        response = client.post("/api/v1/claims", json=payload)
        result = response.json()

        actual_decision = result.get("decision")
        actual_amount = Decimal(str(result.get("approved_amount", 0)))

        decision_match = actual_decision == expected_decision
        amount_match = True
        if actual_decision in ("APPROVED", "PARTIAL"):
            amount_match = actual_amount == expected_amount
        qualitative_notes = _check_system_must(case, result)

        ok = decision_match and amount_match and not qualitative_notes
        passed += int(ok)
        verdict = "PASS" if ok else "FAIL"

        amount_cell = f"{expected_amount} / {actual_amount}" if expected_decision in ("APPROVED", "PARTIAL") or actual_decision in ("APPROVED", "PARTIAL") else "n/a"
        lines.append(f"| {case_id} | {case.get('case_name','')} | {expected_decision} | {actual_decision} | {amount_cell} | {verdict} |")

        section = [f"## {case_id} — {case.get('case_name', '')}", "", f"**Description:** {case.get('description', '')}", ""]
        section.append(f"**Expected:** decision=`{expected_decision}`" + (f", approved_amount=`{expected_amount}`" if expected_decision in ('APPROVED', 'PARTIAL') else ""))
        section.append(f"**Actual:** decision=`{actual_decision}`, approved_amount=`{actual_amount}`, confidence=`{result.get('confidence_score')}`")
        section.append(f"**Reason:** {result.get('reason')}")
        if result.get("fraud_signals"):
            section.append(f"**Fraud signals:** {result['fraud_signals']}")
        if result.get("warnings"):
            section.append(f"**Warnings:** {result['warnings']}")
        if result.get("degraded_components"):
            section.append(f"**Degraded components:** {result['degraded_components']}")
        section.append(f"**Verdict:** {verdict}")
        if not ok:
            explain = []
            if not decision_match:
                explain.append(f"decision mismatch (expected {expected_decision}, got {actual_decision})")
            if not amount_match:
                explain.append(f"amount mismatch (expected {expected_amount}, got {actual_amount})")
            explain.extend(qualitative_notes)
            section.append(f"**Why it didn't match:** {'; '.join(explain)}")
        section.append("")
        section.append("<details><summary>Full trace</summary>")
        section.append("")
        section.append("| # | Component | Rule | Outcome | Effect | Policy Ref | Evidence |")
        section.append("|---|---|---|---|---|---|---|")
        for ev in result.get("trace", []):
            evidence = json.dumps(ev.get("evidence") or {}, ensure_ascii=False)
            ref = ev.get("policy_ref") or ev.get("interpretation_ref") or ""
            section.append(f"| {ev['seq']} | {ev['component']} | {ev.get('rule_id') or ''} | {ev['outcome']} | {ev['effect']} | {ref} | `{evidence}` |")
        section.append("")
        section.append("</details>")
        section.append("")
        detail_sections.append("\n".join(section))

    lines[lines.index("SCORE_PLACEHOLDER")] = f"**Score: {passed}/{len(cases)} passed**"
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.extend(detail_sections)

    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT_FILE} ({passed}/{len(cases)} passed)")


if __name__ == "__main__":
    main()
